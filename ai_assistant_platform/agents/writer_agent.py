from ai_assistant_platform.llm.llm_service import (
    LLMService,
)


class WriterAgent:
    """
    Specialized agent responsible for generating
    user-friendly responses.

    Responsibilities:
        - Transform raw information into natural responses.
        - Preserve the user's language.
        - Improve readability and communication quality.

    Limitations:
        - Never perform calculations.
        - Never invent numerical results.
        - Only use information received from other agents.
    """

    WRITER_PROMPT = """
    You are a Writer Agent.

    Responsibilities:
        - Transform raw information into user-friendly answers.
        - Answer in the same language used by the user.
        - Improve readability.
        - Be clear and concise.

    Restrictions:
        - Never perform calculations.
        - Never invent numbers.
        - Use only the information received.
        - If a mathematical result is provided, only format it.
        - If conversation context is provided, answer using only that context.

    Return only the final answer.
    """

    def __init__(self) -> None:
        """
        Initialize writer agent dependencies.
        """

        self.llm_service = LLMService()

    def generate_response(
        self,
        user_message: str,
        context: object,
    ) -> str:
        """
        Generate a user-friendly response.

        Args:
            user_message:
                Original user message.

            context:
                Information provided by another agent
                or by the orchestrator.

        Returns:
            Natural language response generated by the LLM.
        """

        prompt = f"""
        User message:
        {user_message}

        Available context:
        {context}
        """

        return self.llm_service.generate_response(
            messages=[
                {
                    "role": "system",
                    "content": self.WRITER_PROMPT,
                },
                {
                    "role": "user",
                    "content": prompt,
                },
            ]
        )
