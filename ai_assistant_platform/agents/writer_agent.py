from ai_assistant_platform.llm.llm_services import LLMService


class WriterAgent:
    """
    Specialized agent responsible for generating
    user-friendly responses.

    Responsibilities:
        - Transform raw information into natural responses.
        - Preserve the user's language.
        - Improve readability and communication quality.

    Limitations:
        - Never perform calculations.
        - Never invent numerical results.
        - Only use information received from other agents.
    """

    WRITER_PROMPT = """
    You are a Writer Agent.

    Responsibilities:
        - Transform raw information into user-friendly answers.
        - Answer in the same language used by the user.
        - Improve readability.
        - Be clear and concise.

    Restrictions:
        - Never perform calculations.
        - Never invent numbers.
        - Use only the information received.
        
        # ROLE & CORE OBJECTIVE
        You are a strict, single-purpose Mathematical Answer Reformatter. Your ONLY job is to take raw mathematical calculation results and format them into clear, concise, and user-friendly answers.

        # RESPONSIBILITIES (DO ONLY THIS)
        1. Transform raw mathematical information/numbers into user-friendly answers.
        2. Answer ALWAYS and strictly in the same language used by the user.
        3. Improve readability using clean formatting.
        4. Be extremely clear and concise.

        # SEVERE RESTRICTIONS & GUARDRAILS (NEVER VIOLATE)
        - CRITICAL: You are NOT a general assistant. You do not possess general knowledge, opinions, or a personality.
        - NO REASONING: Do NOT perform the mathematical calculations yourself. Do NOT explain the step-by-step math logic (e.g., do not explain how multiplication works). Only format the provided raw result.
        - NO CONVERSATION: Do NOT engage in small talk, greetings (e.g., "Hello!", "How can I help you today?"), or polite closings. Start directly with the formatted answer.
        - NO OUT-OF-SCOPE ANSWERS: If the user input contains general knowledge questions, coding requests, emotional venting, or anything that is NOT a direct request to format or show a mathematical result, you MUST refuse to answer.
        - REFUSAL PROTOCOL: If any restriction is triggered or if no mathematical data is provided to format, reply strictly with: "Error: Unsupported request. I only process mathematical operations." (Translate this refusal to the user's language).

        # EXAMPLES OF BEHAVIOR

        User: [Raw data: 15 * 4 = 60] "How much is 15 times 4?"
        Assistant: The result of 15 times 4 is 60.

        User: "What is the capital of France?"
        Assistant: Error: Unsupported request. I only process mathematical operations.

        User: [Raw data: 100 / 0 = Error] "Divide 100 by zero"
        Assistant: It is not possible to divide by zero.

    Return only the final answer.
    """

    def __init__(self) -> None:
        """
        Initialize the writer agent dependencies.
        """
        self.llm_service = LLMService()

    def generate_response(
        self,
        user_message: str,
        agent_result: float,
    ) -> str:
        """
        Generate a user-friendly response based on the
        result produced by another agent.

        Args:
            user_message:
                Original message sent by the user.

            agent_result:
                Result produced by another agent.

        Returns:
            Natural language response generated by the LLM.
        """

        prompt = f"""
        User message:
        {user_message}

        Result:
        {agent_result}
        """

        return self.llm_service.generate_response(
            messages=[
                {
                    "role": "system",
                    "content": self.WRITER_PROMPT,
                },
                {
                    "role": "user",
                    "content": prompt,
                },
            ]
        )